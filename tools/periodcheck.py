r"""periodcheck.py - the 1988 librarian and linker accept every module.

usage: python3 -I tools/periodcheck.py [LIB ...]

LIB is a library file named CLIB<k>.LIB, k one of S, C, M, L, H (its
memory model), or the single letter M, L or H for that intact library
read from the zip (the only use of the zip here; a file is checked
without it).  Default: out/CLIBS.LIB and out/CLIBC.LIB.

Two checks per library, each run by Watcom C 6.5's own tools in headless
DOSBox-X (tools/dosrun.py):

1. Extraction by WLIB 1.1.  The library is copied to C:\X and every
   module is extracted by a command file of '*NAME' lines, one per module
   the dictionary names ('WLIB CLIBS @EXT'; the DOS command line holds
   only 127 characters).  Every .OBJ written is identified by its THEADR
   name, not its file name (DOS cuts d_setvect to D_SETVEC), and must be
   byte-identical to the module's bytes in the library, THEADR through
   MODEND without the page padding.  The copy of the library must be
   unchanged afterwards.

2. A link by WLINK 4.1 that pulls in every module.  WLINK 4.1 has no
   REFERENCE directive ('Directive error near ...'), so a C program,
   P.C, is generated that takes the address of every public of the
   library ('extern void NAME(void); #pragma aux NAME "*";' keeps the
   exact name).  It is compiled /m<k> and linked with OPTION MAP,
   NODEFAULTLIBS against the library under test, C:\CLIB<k>.LIB, then
   the intact D:\LIB\MATH<k>.LIB.  OVLLDR, the overlay loader, refers to
   _OVLTAB, the table WLINK builds for an overlaid program, so the link
   has one overlay section (BEGIN SECTION FILE Q END, Q a one-function
   program); for near code it also needs OPTION SMALL, without which
   WLINK asks for the far loader _LOVLLDR ('Missing overlay loader').
   Every line WLINK prints besides its progress lines is a message, and
   only one message is accepted: 'file d:\lib\math<k>.lib(FTOS):
   redefinition of _FtoS_ ignored', which the intact CLIBM, CLIBL and
   CLIBH give too (FTOSX in CLIB<k> and FTOS in MATH<k> both define
   _FtoS_; the table pulls in FTOSX, SCNF's reference to _fltused_ pulls
   in FTOS).  The compiler must print nothing, P.EXE must exist, and the
   module names in the "Defined by" column of the map's memory map, as
   'c:\clib<k>.lib(NAME)', must include every module of the library.

These show that the 1988 librarian and linker accept every module's
records and resolve every public.  They do not show that the code is
right: wrong bytes in valid records pass both.  Neither WLIB 1.1 nor
WLINK 4.1 checks record checksums, so a changed byte inside a record
passes too, with or without its checksum corrected (tools/checklib.py
is the check for that).  A changed public name, or a record length that
breaks a module, fails.

Work files go to build/periodcheck.  Needs build/watcom
(tools/install.py).  Exit status 0 when every library passes both
checks.
"""

import os
import re
import shutil
import sys
from concurrent.futures import ThreadPoolExecutor

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import dosrun  # noqa: E402
import omf  # noqa: E402
import paths  # noqa: E402

WORK = os.path.join(paths.BUILD, 'periodcheck')
TIMEOUT = 300
MAXLINES = 12    # message lines printed per library
MODELS = 'SCMLH'


def modules(lib):
    """[(module name, its bytes THEADR..MODEND)] in library order.  The
    records are walked by their lengths, checksums unchecked, so that what
    WLIB and WLINK make of a bad record is what is tested; raises
    ValueError when a module has no THEADR or no MODEND in its span."""
    out = []
    d = lib.data
    for s in lib.starts:
        e = lib.span(s)[1]
        i = s
        while i + 3 <= e:
            t = d[i]
            i += 3 + (d[i + 1] | d[i + 2] << 8)
            if t in omf.MODEND:
                break
        if d[s] not in omf.MODSTART or t not in omf.MODEND or i > e:
            raise ValueError('module at offset %d: no THEADR..MODEND in '
                             'its page span' % s)
        b = d[s:i]
        out.append((b[4:4 + b[3]].decode('latin1'), b))
    return out


def publics(lib):
    return [n for s in lib.starts for n in lib.names[s]
            if not n.endswith('!')]


def program(names):
    """C source that takes the address of every name."""
    src = ['/* generated by tools/periodcheck.py */']
    for n in names:
        src += ['extern void %s( void );' % n, '#pragma aux %s "*";' % n]
    src += ['void (*periodcheck_table[])( void ) = {']
    src += ['    %s,' % n for n in names]
    src += ['};', '', 'int main( void )', '{', '    return( 0 );', '}']
    return src


def batch(k):
    return ['@echo off',
            'CD X',
            'WLIB CLIB%s @EXT > ..\\WLIB.LOG' % k,
            'CD \\',
            'WCC P.C /m%s /zq > CC.LOG' % k.lower(),
            'WCC Q.C /m%s /zq > CCQ.LOG' % k.lower(),
            'WLINK @P > LINK.LOG']


def prepare(d, k, data, lib):
    """Write the work dir d for library bytes data of model k."""
    if os.path.isdir(d):
        shutil.rmtree(d)
    x = os.path.join(d, 'X')
    os.makedirs(x)
    for where in (x, d):
        with open(os.path.join(where, 'CLIB%s.LIB' % k), 'wb') as f:
            f.write(data)
    with open(os.path.join(x, 'EXT.CMD'), 'w', newline='\r\n') as f:
        f.write(''.join('*%s\n' % n for n, b in modules(lib)))
    with open(os.path.join(d, 'P.C'), 'w', newline='\r\n') as f:
        f.write('\n'.join(program(publics(lib))) + '\n')
    with open(os.path.join(d, 'Q.C'), 'w', newline='\r\n') as f:
        f.write('int periodcheck_overlay( void ) { return( 1 ); }\n')
    with open(os.path.join(d, 'P.LNK'), 'w', newline='\r\n') as f:
        f.write('FILE P\nNAME P\nOPTION MAP, NODEFAULTLIBS%s\n'
                'LIBRARY C:\\CLIB%s, D:\\LIB\\MATH%s\n'
                'BEGIN SECTION FILE Q END\n' %
                (', SMALL' if k in 'SC' else '', k, k))
    with open(os.path.join(d, 'GO.BAT'), 'w', newline='\r\n') as f:
        f.write('\n'.join(batch(k)) + '\n')


def read(p):
    return open(p, errors='replace').read() if os.path.exists(p) else ''


def check_extract(d, k, data, lib):
    """(ok, lines)."""
    x = os.path.join(d, 'X')
    want = dict(modules(lib))
    got = {}
    bad = []
    for f in sorted(os.listdir(x)):
        if not f.upper().endswith('.OBJ'):
            continue
        b = open(os.path.join(x, f), 'rb').read()
        try:
            name = omf.theadr([(b[0], b[3:3 + (b[1] | b[2] << 8) - 1], 0)])
        except IndexError:
            bad.append('%s: not an object file' % f)
            continue
        if name in got:
            bad.append('%s: %s extracted twice' % (f, name))
        got[name] = b
    same = [n for n in want if got.get(n) == want[n]]
    for n in want:
        if n not in got:
            bad.append('%s: not extracted' % n)
        elif got[n] != want[n]:
            bad.append('%s: differs from the library (%s)' % (
                n, record_diff(want[n], got[n])))
    for n in got:
        if n not in want:
            bad.append('%s: extracted but not in the library' % n)
    with open(os.path.join(x, 'CLIB%s.LIB' % k), 'rb') as f:
        if f.read() != data:
            bad.append('WLIB changed the library')
    log = read(os.path.join(d, 'WLIB.LOG'))
    if 'rror' in log or 'arning' in log:
        bad.append('WLIB: ' + log.strip())
    lines = ['%d modules extracted, %d identical' % (len(got), len(same))]
    return not bad and len(same) == len(want), lines + bad


def records(b):
    out = []
    i = 0
    while i + 3 <= len(b):
        n = b[i + 1] | b[i + 2] << 8
        out.append((i, b[i:i + 3 + n]))
        i += 3 + n
    return out


def record_diff(a, b):
    """Where object b first differs from a, record by record."""
    ra, rb = records(a), records(b)
    for (i, x), (j, y) in zip(ra, rb):
        if x != y:
            return 'record %02Xh at %d: %s vs %s' % (x[0], i, x.hex(),
                                                     y.hex())
    return '%d records vs %d, %d bytes vs %d' % (len(ra), len(rb), len(a),
                                                len(b))


# WLINK's progress lines; any other line of its output is a message
PROGRESS = ('WATCOM Linker Version 4.1', 'Copyright by WATCOM Systems Inc.',
            'Loading object files', 'Searching libraries',
            'Creating map file', 'Creating executable file')
# the one message accepted, the same with the intact CLIBM, CLIBL, CLIBH:
# FTOSX (CLIB<k>) and FTOS (MATH<k>) both define _FtoS_; the table pulls
# in FTOSX, and SCNF's reference to _fltused_ pulls in FTOS
FTOS = r'file d:\lib\math%s.lib(FTOS): redefinition of _FtoS_ ignored'
# a symbol line of the map's memory map: address, '*' when unreferenced,
# symbol, and the file(module) that defines it (given on the first
# symbol of each module)
MAPSYM = re.compile(r'^[0-9a-f]{4}:[0-9a-f]{4}\*? +\S+ +(\S+)\((\w+)\)$')


def map_modules(text, k):
    """Names of the modules of the map's memory map that come from
    C:\\CLIB<k>.LIB."""
    out = set()
    body = text.split('Memory Map', 1)[1] if 'Memory Map' in text else ''
    for line in body.splitlines():
        m = MAPSYM.match(line.strip())
        if m and m.group(1).lower() == 'c:\\clib%s.lib' % k.lower():
            out.add(m.group(2))
    return out


def check_link(d, k, lib):
    """(ok, lines)."""
    bad = []
    for log in ('CC.LOG', 'CCQ.LOG'):
        text = read(os.path.join(d, log)).strip()
        if text:
            bad.append('%s:\n%s' % (log, text))
    msgs = [x.strip() for x in read(os.path.join(d, 'LINK.LOG'))
            .splitlines() if x.strip() and not x.startswith(PROGRESS)]
    extra = [x for x in msgs if x != FTOS % k.lower()]
    if extra or not os.path.exists(os.path.join(d, 'P.EXE')):
        # errors first, each distinct message once with its count
        uniq = sorted(set(msgs), key=lambda x: ('Error' not in x,
                                                msgs.index(x)))
        bad.append('WLINK:\n' + '\n'.join(
            ['%s%s' % (x, ' (%d times)' % msgs.count(x)
                       if msgs.count(x) > 1 else '') for x in uniq] or
            ['(no P.EXE)']))
    text = read(os.path.join(d, 'P.MAP'))
    if not text:
        bad.append('no map (P.MAP)')
    linked = map_modules(text, k)
    want = [n for n, b in modules(lib)]
    have = [n for n in want if n in linked]
    missing = [n for n in want if n not in linked]
    if 'Memory Map' not in text:
        bad.append('the map has no memory map (the link stopped)')
    elif missing:
        bad.append('not linked: %s%s' % (' '.join(missing[:10]), ' and %d '
                   'more' % (len(missing) - 10) if len(missing) > 10 else ''))
    lines = ['%d of %d modules linked' % (len(have), len(want))]
    return not bad, lines + bad


def target(arg):
    """(label, model letter, library bytes)."""
    if arg.upper() in ('M', 'L', 'H'):
        k = arg.upper()
        paths.check_zip()       # only these targets read the zip
        return 'zip CLIB%s.LIB' % k, k, paths.library_bytes(k)
    base = os.path.basename(arg).upper()
    if not re.match(r'CLIB[%s]\.LIB$' % MODELS, base):
        raise SystemExit('%s: name must be CLIB<model>.LIB, model one of '
                         '%s' % (arg, ', '.join(MODELS)))
    with open(arg, 'rb') as f:
        return arg, base[4], f.read()


def show(label, ok, lines):
    print('%s: %s' % (label, 'ok' if ok else 'FAILED'))
    out = [y for x in lines for y in x.split('\n')]
    for line in out[:MAXLINES]:
        print('  ' + line)
    if len(out) > MAXLINES:
        print('  (%d more lines in %s)' % (len(out) - MAXLINES, WORK))


def main(argv):
    args = argv[1:] or [os.path.join(paths.OUT, 'CLIBS.LIB'),
                        os.path.join(paths.OUT, 'CLIBC.LIB')]
    if any(a.startswith('-') for a in args):
        sys.stderr.write(__doc__.split('\n\n')[1] + '\n')
        return 2
    if os.path.isdir(WORK):
        shutil.rmtree(WORK)
    jobs = []
    for n, a in enumerate(args):
        label, k, data = target(a)
        try:
            lib = omf.Lib.from_bytes(data, label)
            modules(lib)
        except (ValueError, IndexError) as e:
            jobs.append((label, k, data, None,
                         'does not read as a library: %s' % e))
            continue
        d = os.path.join(WORK, '%d-CLIB%s' % (n, k))
        prepare(d, k, data, lib)
        jobs.append((label, k, data, lib, d))
    with ThreadPoolExecutor(4) as ex:
        done = list(ex.map(lambda j: j[3] is not None and
                           dosrun.run(j[4], 'GO.BAT', TIMEOUT), jobs))
    status = 0
    for (label, k, data, lib, d), fin in zip(jobs, done):
        if lib is None:
            show(label, False, [d])
            status = 1
            continue
        ok1, l1 = check_extract(d, k, data, lib)
        ok2, l2 = check_link(d, k, lib)
        if not fin:
            l2.append('DOSBox-X did not end normally (timeout or failure)')
        ok = ok1 and ok2 and fin
        show(label, ok, l1 + l2)
        if not ok:
            status = 1
    return status


if __name__ == '__main__':
    sys.exit(main(sys.argv))
